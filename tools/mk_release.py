"""The release as one QDOS job (src/rel_job.asm).

    python tools/mk_release.py [build_dir]

In the build folder (build_rel/ for build_release.sh), from its mmr, proto_r.lst,
mm_dat and mm_dat.json:
  rel/mmr.zx0            the release code (mmr) ZX0-packed
  rel/rel_eq.inc         the stub's figures: the regions' sizes, mm_dat's length, the
                         globals' offsets (proto_r.lst, as mmr_bas pokes them)
  mm                     the job (stub + packed code), raw
  release/mm.mdv         a microdrive cartridge image (QLay format, tools/mkmdv.py):
                         BOOT, mm (type 1, its dataspace), mm_dat
  release/win/           the same files for a host folder (Q-emuLator, QPC2, sQLux):
                         mm carries Q-emuLator's 30-byte "]!QDOS File Header"
  release/cache/, release/mm_cache.mdv   the same with the cache readout on

The assembler: $VASM, else vasmm68k_mot on the PATH.

The job's dataspace: from the packed code's place (DEST), the code, the race area, the
bitmap, the marble bank and mm_dat (each rounded to 4), then STACK_KEEP and QDOS's 512
for the job stack, less the file's own length. The sprite cache is allocated by the stub
(MT.ALCHP) from what is left.
"""
import os
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import mk_proto_loader as ML  # noqa: E402
import mkmdv  # noqa: E402

VASM = os.environ.get('VASM', 'vasmm68k_mot')
STACK_KEEP = 1024
QEMU_MAGIC = b']!QDOS File Header'
OFFS = ('G_TLOGO', 'G_CCH', 'G_CSZ', 'G_RBUF', 'G_LIN', 'G_SPRB', 'G_DAT', 'G_SAVE', 'G_TAKE',
        'G_TAUD', 'G_TFPS', 'G_TKERR')


def r4(n):
    return (n + 3) & ~3


def qemulator_header(typ, dataspace, extra=0):
    """Q-emuLator's header prefix for files in a host folder: the ID, 0, the length in
    words (15 = 30 bytes), then bytes 4..13 of the QDOS header (access, type, dataspace,
    extra)"""
    return QEMU_MAGIC + bytes([0, 15]) + struct.pack('>BBII', 0, typ, dataspace, extra)


def boot(dev):
    return ('10 EXEC_W %smm\n' % dev).encode('latin-1')


def main():
    b = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'build'
    rel = b / 'rel'
    rel.mkdir(exist_ok=True)
    eq = ML.equates(b / 'proto_r.lst')
    bu = ML.buffers(b)
    code = (b / 'mmr').read_bytes()
    dat = (b / 'mm_dat').read_bytes()
    import zx0pack
    packed = zx0pack.zx0_many([code])[0]
    (rel / 'mmr.zx0').write_bytes(packed)
    reg = {'CODE_A': r4(len(code)), 'AREA_A': r4(bu['area']), 'LIN_A': r4(bu['lin']),
           'SPR_A': r4(bu['spr']), 'DSZ': len(dat), 'DSZ_A': r4(len(dat))}
    need = reg['CODE_A'] + reg['AREA_A'] + reg['LIN_A'] + reg['SPR_A'] + reg['DSZ_A']
    inc = ['; GENERATED by tools/mk_release.py - do not edit.']
    inc += ['%-15s equ %d' % (k, v) for k, v in reg.items()]
    inc += ['%-15s equ %d' % ('NEED', need), '%-15s equ %d' % ('PACKED_LEN', len(packed)),
            '%-15s equ %d' % ('CC_SPARE', ML.CC_SPARE)]
    inc += ['%-15s equ %d' % ('O_' + k[2:], ML.G + eq[k]) for k in OFFS]
    (rel / 'rel_eq.inc').write_text('\n'.join(inc) + '\n', newline='\n')
    r = subprocess.run([VASM, '-Fbin', '-m68000', '-quiet', '-I', str(rel), '-I', str(ROOT / 'src'),
                        '-L', str(rel / 'rel_job.lst'), '-o', str(b / 'mm'),
                        str(ROOT / 'src' / 'rel_job.asm')], capture_output=True, text=True)
    out = r.stdout + r.stderr
    if r.returncode or 'arning' in out or 'rror' in out:
        print(out)
        sys.exit('mk_release: vasm failed (a warning counts)')
    job = (b / 'mm').read_bytes()
    dest = job.find(packed)
    assert dest > 0 and dest % 4 == 0 and job.find(packed, dest + 1) < 0, dest
    ds = (dest + need + STACK_KEEP + 512 - len(job) + 15) & ~15
    # the cartridge, and the host folder
    files = [('BOOT', boot('mdv1_'), 0, 0), ('mm', job, 1, ds), ('mm_dat', dat, 0, 0)]
    out_dir = b / 'release'
    (out_dir / 'win').mkdir(parents=True, exist_ok=True)
    img, info = mkmdv.build(files, 'MARBLE')
    p = mkmdv.parse(img)
    assert not p['bad_checksums']
    for (n, d, t, dsp), f in zip(files, p['files']):
        assert f['name'] == n and f['data'] == d and f['type'] == t and f['dataspace'] == dsp, n
    (out_dir / 'mm.mdv').write_bytes(img)
    (out_dir / 'win' / 'BOOT').write_bytes(boot('win1_'))
    (out_dir / 'win' / 'mm').write_bytes(qemulator_header(1, ds) + job)
    (out_dir / 'win' / 'mm_dat').write_bytes(dat)
    # the same with the cache readout on (settings +34 = 1): release/cache/ and
    # release/mm_cache.mdv
    jc = bytearray(job)
    assert jc[16:20] == b'MMCF' and jc[34] == 0
    jc[34] = 1
    (out_dir / 'cache').mkdir(parents=True, exist_ok=True)
    (out_dir / 'cache' / 'BOOT').write_bytes(boot('win1_'))
    (out_dir / 'cache' / 'mm').write_bytes(qemulator_header(1, ds) + bytes(jc))
    (out_dir / 'cache' / 'mm_dat').write_bytes(dat)
    (out_dir / 'mm_cache.mdv').write_bytes(mkmdv.build(
        [('BOOT', boot('mdv1_'), 0, 0), ('mm', bytes(jc), 1, ds), ('mm_dat', dat, 0, 0)], 'MARBLE')[0])
    sec = [(len(d) + 64 + 511) // 512 for _, d, _, _ in files]
    print('release job %s: stub %d B + code %d -> %d B ZX0 = %d B, dataspace %d '
          '(job area %d: code %d, race area %d, bitmap %d, marble %d, mm_dat %d, stack %d)'
          % ((b / 'mm').as_posix(), dest, len(code), len(packed), len(job), ds, len(job) + ds, reg['CODE_A'],
             reg['AREA_A'], reg['LIN_A'], reg['SPR_A'], reg['DSZ_A'], STACK_KEEP + 512))
    used = info['used']                     # (with the map and the directory)
    assert used == sum(sec) + 2, (used, sec)
    print('release cartridge %s: BOOT %d + mm %d + mm_dat %d sectors + map '
          'and directory 2 = %d sectors (%.1f KB); free on a 200-sector cartridge (the '
          'minimum): %d, on 220 (typical): %d'
          % ((out_dir / 'mm.mdv').as_posix(), sec[0], sec[1], sec[2], used, used / 2, 200 - used, 220 - used))


if __name__ == '__main__':
    main()
